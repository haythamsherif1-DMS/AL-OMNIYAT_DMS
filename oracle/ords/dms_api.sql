  END;

  FUNCTION upsert_DMS_SERIALS_(p_body CLOB) RETURN NUMBER IS
  BEGIN
    MERGE INTO DMS_SERIALS t
    USING (
      SELECT * FROM JSON_TABLE(p_body, '$.rows[*]' COLUMNS (
          SERIAL_ID VARCHAR2(100 CHAR) PATH '$.SerialID',
          SERIAL_NO CLOB PATH '$.SerialNo',
          KIND CLOB PATH '$.Kind',
          COMPANY_ID CLOB PATH '$.CompanyID',
          PROJECT_ID CLOB PATH '$.ProjectID',
          YEAR_NO NUMBER PATH '$.Year',
          SEQ NUMBER PATH '$.Seq',
          ISSUE_DATE VARCHAR2(40) PATH '$.IssueDate',
          SUBJECT CLOB PATH '$.Subject',
          PARTY CLOB PATH '$.Party',
          AMOUNT NUMBER PATH '$.Amount',
          CURRENCY CLOB PATH '$.Currency',
          SIGNERS CLOB PATH '$.Signers',
          NOTES CLOB PATH '$.Notes',
          DOC_ID CLOB PATH '$.DocID',
          STATUS CLOB PATH '$.Status',
          CREATED_BY CLOB PATH '$.CreatedBy',
          CREATED_AT VARCHAR2(40) PATH '$.CreatedAt',
          SHEET_ROW NUMBER PATH '$._row'))
      WHERE SERIAL_ID IS NOT NULL
    ) s
    ON (t.SERIAL_ID = s.SERIAL_ID)
    WHEN MATCHED THEN UPDATE SET
      t.SERIAL_NO = s.SERIAL_NO,
      t.KIND = s.KIND,
      t.COMPANY_ID = s.COMPANY_ID,
      t.PROJECT_ID = s.PROJECT_ID,
      t.YEAR_NO = s.YEAR_NO,
      t.SEQ = s.SEQ,
      t.ISSUE_DATE = TO_TIMESTAMP(SUBSTR(s.ISSUE_DATE, 1, 19) DEFAULT NULL ON CONVERSION ERROR, 'YYYY-MM-DD"T"HH24:MI:SS'),
      t.SUBJECT = s.SUBJECT,
      t.PARTY = s.PARTY,
      t.AMOUNT = s.AMOUNT,
      t.CURRENCY = s.CURRENCY,
      t.SIGNERS = s.SIGNERS,
      t.NOTES = s.NOTES,
      t.DOC_ID = s.DOC_ID,
      t.STATUS = s.STATUS,
      t.CREATED_BY = s.CREATED_BY,
      t.CREATED_AT = TO_TIMESTAMP(SUBSTR(s.CREATED_AT, 1, 19) DEFAULT NULL ON CONVERSION ERROR, 'YYYY-MM-DD"T"HH24:MI:SS'),
      t.SHEET_ROW = NVL(s.SHEET_ROW, t.SHEET_ROW),
      t.MIGRATED_AT = SYSTIMESTAMP
    WHEN NOT MATCHED THEN INSERT (SERIAL_ID, SERIAL_NO, KIND, COMPANY_ID, PROJECT_ID, YEAR_NO, SEQ, ISSUE_DATE, SUBJECT, PARTY, AMOUNT, CURRENCY, SIGNERS, NOTES, DOC_ID, STATUS, CREATED_BY, CREATED_AT, SHEET_ROW)
      VALUES (s.SERIAL_ID, s.SERIAL_NO, s.KIND, s.COMPANY_ID, s.PROJECT_ID, s.YEAR_NO, s.SEQ, TO_TIMESTAMP(SUBSTR(s.ISSUE_DATE, 1, 19) DEFAULT NULL ON CONVERSION ERROR, 'YYYY-MM-DD"T"HH24:MI:SS'), s.SUBJECT, s.PARTY, s.AMOUNT, s.CURRENCY, s.SIGNERS, s.NOTES, s.DOC_ID, s.STATUS, s.CREATED_BY, TO_TIMESTAMP(SUBSTR(s.CREATED_AT, 1, 19) DEFAULT NULL ON CONVERSION ERROR, 'YYYY-MM-DD"T"HH24:MI:SS'), s.SHEET_ROW);
    RETURN SQL%ROWCOUNT;
  END;

