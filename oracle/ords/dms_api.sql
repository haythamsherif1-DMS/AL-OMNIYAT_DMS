  FUNCTION err_(p_msg VARCHAR2) RETURN CLOB IS
    l CLOB;
  BEGIN
    SELECT JSON_OBJECT('ok' VALUE 'false' FORMAT JSON, 'error' VALUE SUBSTR(p_msg, 1, 1000) RETURNING CLOB) INTO l FROM dual;
    RETURN l;
  END;

