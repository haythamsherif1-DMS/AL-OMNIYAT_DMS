  FUNCTION upsert_DMS_SECTORS_(p_body CLOB) RETURN NUMBER IS
  BEGIN
    MERGE INTO DMS_SECTORS t
    USING (
      SELECT * FROM JSON_TABLE(p_body, '$.rows[*]' COLUMNS (
          SECTOR_ID VARCHAR2(100 CHAR) PATH '$.SectorID',
          SECTOR_NAME CLOB PATH '$.SectorName',
          SORT_ORDER NUMBER PATH '$.SortOrder',
          ACTIVE CLOB PATH '$.Active',
          NOTES CLOB PATH '$.Notes',
          SHEET_ROW NUMBER PATH '$._row'))
      WHERE SECTOR_ID IS NOT NULL
    ) s
    ON (t.SECTOR_ID = s.SECTOR_ID)
    WHEN MATCHED THEN UPDATE SET
      t.SECTOR_NAME = s.SECTOR_NAME,
      t.SORT_ORDER = s.SORT_ORDER,
      t.ACTIVE = s.ACTIVE,
      t.NOTES = s.NOTES,
      t.SHEET_ROW = NVL(s.SHEET_ROW, t.SHEET_ROW),
      t.MIGRATED_AT = SYSTIMESTAMP
    WHEN NOT MATCHED THEN INSERT (SECTOR_ID, SECTOR_NAME, SORT_ORDER, ACTIVE, NOTES, SHEET_ROW)
      VALUES (s.SECTOR_ID, s.SECTOR_NAME, s.SORT_ORDER, s.ACTIVE, s.NOTES, s.SHEET_ROW);
    RETURN SQL%ROWCOUNT;
  END;

